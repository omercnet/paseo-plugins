// Regenerates server/docker/image.ts from runtime/Dockerfile. The plugin bundle cannot read
// sibling files at run time, so the Dockerfile text ships inside the server module.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const lines = readFileSync(`${root}runtime/Dockerfile`, "utf8").replace(/\n$/, "").split("\n");
const body = lines.map((line) => `  ${JSON.stringify(line)},`).join("\n");
writeFileSync(
  `${root}server/docker/image.ts`,
  `import { createHash } from "node:crypto";

// Generated by scripts/embed-dockerfile.mjs from runtime/Dockerfile. Do not edit by hand.
export const DOCKERFILE = [
${body}
  "",
].join("\\n");

/** The tag changes with the Dockerfile, so an upgraded plugin builds its own image once. */
export const IMAGE_TAG = \`paseo-sandbox:\${createHash("sha256").update(DOCKERFILE).digest("hex").slice(0, 12)}\`;
`,
);
